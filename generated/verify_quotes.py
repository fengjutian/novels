def chap(n):
    hits = glob.glob(os.path.join(ROOT, "第%02d章*.md" % n))
    if not hits:
        hits = glob.glob(os.path.join(ROOT, "第%d章*.md" % n))
    if not hits:
        return None
    return open(hits[0], encoding="utf-8").read()

def others(name):
    p = os.path.join(ROOT, "others", name)
    return open(p, encoding="utf-8").read()

