# ---------------------------------------------------------------- 执行
def load(path):
    raw = open(path, "rb").read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    txt = raw.decode("utf-8-sig")
    return txt, bom

def save(path, txt, bom):
    data = txt.encode("utf-8")
    if bom:
        data = b"\xef\xbb\xbf" + data
    with open(path, "wb") as f:
        f.write(data)

# 归组
groups = {}
for target, old, new, cnt, note in EDITS:
    p = chap_path(target[1]) if target[0] == "ch" else oth_path(target[1])
    groups.setdefault(p, []).append((old, new, cnt, note))

print("=" * 74)
print("《赤潮北境》审稿报告 §E-1 第 2 批（零风险改动）  共 %d 条" % len(EDITS))
print("=" * 74)

errors = []
plans = []
for p, items in groups.items():
    txt, bom = load(p)
    ok = True
    for old, new, cnt, note in items:
        got = txt.count(old)
        if got != cnt:
            errors.append("  [%s] 命中 %d 次（期望 %d）：%s" %
                          (os.path.basename(p), got, cnt, note))
            ok = False
            continue
        txt = txt.replace(old, new)
    if ok:
        plans.append((p, bom, txt, len(items)))

if errors:
    print("\n断言失败，未写盘：")
    for e in errors:
        print(e)
    sys.exit(1)

if DRY:
    print("\n--dry 模式：断言全部通过，未写盘。共 %d 处改动，涉及 %d 个文件。" %
          (len(EDITS), len(plans)))
    for p, _, _, n in plans:
        print("   %-40s %d 处" % (os.path.basename(p), n))
    sys.exit(0)

# 备份
if os.path.isdir(BACKUP):
    shutil.rmtree(BACKUP)
os.makedirs(BACKUP)
for p in groups:
    shutil.copy2(p, os.path.join(BACKUP, os.path.basename(p)))
print("\n已备份 %d 个文件到 generated/_fix1_backup/" % len(groups))

# 写盘
for p, bom, txt, n in plans:
    save(p, txt, bom)
    print("  写入 %-40s %d 处" % (os.path.basename(p), n))

print("\n完成：%d 处改动，%d 个文件。" % (len(EDITS), len(plans)))
